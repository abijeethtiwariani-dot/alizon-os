// Builds pvx-certificate-roster.js from a plain list of names, one per line.
//   node tools-pvx-cert-roster.mjs names.txt
// A name already in the roster KEEPS its code, so re-running after a spelling
// fix or a late addition never invalidates a certificate already downloaded.
// To correct a spelling without changing the code, edit the roster file itself.
import fs from 'node:fs';
import crypto from 'node:crypto';
const OUT = new URL('./pvx-certificate-roster.js', import.meta.url);
const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';   // no I/O/0/1, as in alizon-certificate.js
const key = s => s.toUpperCase().replace(/[^A-Z]/g, '');
let old = { people: [] };
try { const src = fs.readFileSync(OUT, 'utf8'); old = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1)); } catch {}
const byName = new Map(old.people.map(p => [key(p.name), p]));
const used = new Set(old.people.map(p => p.code));
const code = () => { let c; do { c = 'ALZ/2026/PVX/' + [...crypto.randomBytes(6)].map(b => ALPHABET[b % 32]).join(''); } while (used.has(c)); used.add(c); return c; };
const names = fs.readFileSync(process.argv[2], 'utf8').split('\n').map(s => s.trim().replace(/\s+/g, ' ')).filter(Boolean);
const people = names.map(n => byName.get(key(n)) || { name: n, code: code() });
const roster = {
  workshop: old.workshop || 'PV-X — AI ADR Detective',
  subtitle: old.subtitle || 'Pharmacovigilance through virtual-patient simulation',
  date: old.date || '9 September 2026',
  hours: old.hours || 8,
  issued: old.issued || '8 October 2026',   // date printed on the experience letter
  institution: old.institution || 'Mar Dioscorus College of Pharmacy',
  people
};
fs.writeFileSync(OUT, '/* Generated by tools-pvx-cert-roster.mjs — the participants of the PV-X hands-on workshop.\n'
  + '   Spelling can be fixed here directly; keep each code unchanged. */\nwindow.PVX_ROSTER = '
  + JSON.stringify(roster, null, 1) + ';\n');
console.log(people.length + ' people, ' + people.filter(p => !byName.has(key(p.name))).length + ' new');
