/* tools-build-programme-catalogue.js — public programme/module inventory.
   node tools-build-programme-catalogue.js  →  programme-catalogue.json

   Course structure only: programmes, modules, units and which practicals are
   live. Contains NO student data of any kind — it is generated from the
   DEFAULT_PROGRAMS literal in the dashboard, which is course content, and is
   safe to serve publicly. */
const fs = require('fs');

const src = fs.readFileSync('ASMDI-dashboard.html', 'utf8');
const m = src.match(/const DEFAULT_PROGRAMS\s*=\s*\[[\s\S]*?\n\];/);
if (!m) { console.error('DEFAULT_PROGRAMS not found'); process.exit(1); }
const PROGRAMS = new Function(m[0] + ' return DEFAULT_PROGRAMS;')();

const cat = PROGRAMS.map(p => {
  const modules = (p.modules || []).map(mo => ({
    unit: mo.unit || '',
    title: mo.title || '',
    desc: mo.desc || '',
    status: mo.status || 'soon',
    units: (mo.units || []).length,
    practicals: (mo.practicals || []).map(x => x.title || '')
  }));
  return {
    id: p.id, name: p.name || '', course: p.course || '',
    modules,
    stats: {
      modules: modules.length,
      live: modules.filter(x => x.status === 'live').length,
      practicals: modules.reduce((n, x) => n + x.practicals.length, 0),
      units: modules.reduce((n, x) => n + x.units, 0)
    }
  };
});

const totals = {
  programmes: cat.length,
  modules: cat.reduce((n, p) => n + p.stats.modules, 0),
  liveModules: cat.reduce((n, p) => n + p.stats.live, 0),
  practicals: cat.reduce((n, p) => n + p.stats.practicals, 0),
  units: cat.reduce((n, p) => n + p.stats.units, 0)
};

fs.writeFileSync('programme-catalogue.json',
  JSON.stringify({ note: 'generated by tools-build-programme-catalogue.js — course structure only, no student data', totals, programmes: cat }, null, 1));

console.log('TOTALS:', JSON.stringify(totals));
cat.forEach(p => console.log(`  ${p.id.padEnd(12)} ${String(p.stats.modules).padStart(2)} modules  ${String(p.stats.live).padStart(2)} live  ${String(p.stats.practicals).padStart(2)} practicals  ${p.name}`));
console.log('size:', (fs.statSync('programme-catalogue.json').size/1024).toFixed(1), 'KB');
